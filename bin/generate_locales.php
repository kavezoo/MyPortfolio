function poEscape(string $s): string
{
    return addcslashes($s, "\\\"\n\r\t");
}

function writePo(string $path, string $locale, array $entries): void
{
    $lines = [
        'msgid ""',
        'msgstr ""',
        '"Project-Id-Version: MyPortfolio\n"',
        '"Language: ' . $locale . '\n"',
        '"MIME-Version: 1.0\n"',
        '"Content-Type: text/plain; charset=UTF-8\n"',
        '"Content-Transfer-Encoding: 8bit\n"',
        '"Plural-Forms: nplurals=2; plural=(n != 1);\n"',
        '',
    ];

    foreach ($entries as $id => $str) {
        $lines[] = 'msgid "' . poEscape($id) . '"';
        $lines[] = 'msgstr "' . poEscape($str) . '"';
        $lines[] = '';
    }

    $dir = dirname($path);
    if (!is_dir($dir)) {
        mkdir($dir, 0777, true);
    }
    file_put_contents($path, implode("\n", $lines));
}

